// Extracts every spoken line from index.html into tools/lines.json,
// and writes audio-map.js mapping "who|text" -> audio file per language.
// Run: node tools/extract-lines.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { createHash } from 'crypto';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');

function slice(name, open, close){
  const start = html.indexOf(`const ${name} = ${open}`);
  if(start < 0) throw new Error(`cannot find ${name}`);
  const end = html.indexOf(`\n${close};`, start);
  if(end < 0) throw new Error(`cannot find end of ${name}`);
  return html.slice(start, end + close.length + 2);
}

const src = [
  slice('CHARS','{','}'),
  slice('SCENES','[',']'),
  slice('BUILDS','[',']'),
  slice('THINGS','[',']'),
  `const ES_NUM = ['cero','uno','dos','tres','cuatro','cinco','seis','siete','ocho','nueve','diez','once','doce'];`,
  `const EN_NUM = ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve'];`,
].join('\n');

const { CHARS, SCENES, BUILDS, THINGS, ES_NUM, EN_NUM } =
  new Function(src + '\nreturn {CHARS, SCENES, BUILDS, THINGS, ES_NUM, EN_NUM};')();

const seen = new Set(), entries = [];
function add(who, lang, text){
  if(!text) return;
  const k = who + '|' + lang + '|' + text;
  if(seen.has(k)) return;
  seen.add(k);
  entries.push({ w: who, l: lang, t: text });
}

// Scenes: character narration + replies in character voice, options in "you"
for(const s of SCENES) for(const b of s.beats){
  if(b.say){ add(b.say.who,'en',b.say.t); add(b.say.who,'es',b.say.es); }
  if(b.pick) for(const o of b.pick){
    add('you','en',o.t); add('you','es',o.es);
    add(o.reply.who,'en',o.reply.t); add(o.reply.who,'es',o.reply.es);
  }
}
// Stage C own-words option and its reply from every character
add('you','en',"I have my own thing to say."); add('you','es',"Tengo algo mío que decir.");
for(const c of Object.keys(CHARS)){
  add(c,'en',"Say it out loud! Your own words are my favorite words.");
  add(c,'es',"¡Dilo en voz alta! Tus propias palabras son mis favoritas.");
}
// Builder: every composed variant (first swap === the whole phrase)
for(const b of BUILDS) for(const s of b.swaps) add('you','en',`${b.pre} ${s.t}${b.post}`);
// Number room: every sentence both languages, plus times-table lines
for(let n=1;n<=12;n++){
  for(const t of THINGS){
    add('you','en',`There ${n===1?'is':'are'} ${n} ${n===1?t.en:t.enp}.`);
    add('you','es',`Hay ${ES_NUM[n]} ${n===1?t.es:t.esp}.`);
  }
  add('you','en',`The ${EN_NUM[n]} times table.`);
}
// Music room ear games — Coco's lines for guess-the-note and copy-me
const NOTE_SAY = ['C','C sharp','D','D sharp','E','F','F sharp','G','G sharp','A','A sharp','B','high C'];
for(const n of NOTE_SAY){
  add('coco','en',`That's it! ${n}!`);
  add('coco','en',`It was ${n}. Listen again!`);
}
add('coco','en',"Listen. Which note is this?");
add('coco','en',"My turn. Listen carefully.");
add('coco','en',"Your turn. Play it back!");
add('coco','en',"You copied it! Let's add one more note.");
add('coco','en',"Almost! Here it is again.");
add('coco','en',"You have very good ears.");
add('coco','en',"Listen. Then sing it back!");
add('coco','en',"Your turn. Sing it!");
add('coco','en',"Sing anything. I will tell you the note.");
add('coco','en',"The microphone is shy today. Ask a grown-up to help.");
// Voice test + attic (the house speaks)
add('you','en',"Hi Sasha! Come in, come in.");
add('house','en',"Good morning. The attic is stretching and yawning.");
add('house','en',"The attic is warm and dusty and happy.");
add('house','en',"The attic is getting sleepy.");
add('house','en',"Shh. The attic is where the house dreams.");
add('house','en',"Things you say a lot float up here.");

/* Content-hash filenames: a line keeps its file forever, an edited line gets
   a new one. Index-based names would silently re-pair texts with the wrong
   recordings whenever a line is added or changed. */
entries.forEach(e=>{
  e.f = 'audio/' + createHash('sha1').update(e.w+'|'+e.l+'|'+e.t).digest('hex').slice(0,12) + '.mp3';
});
mkdirSync(join(root,'audio'), {recursive:true});
writeFileSync(join(root,'tools/lines.json'), JSON.stringify(entries));

const map = { en:{}, es:{} };
for(const e of entries) map[e.l][e.w + '|' + e.t] = e.f;
writeFileSync(join(root,'audio-map.js'),
  '// Generated by tools/extract-lines.mjs — do not edit by hand\n' +
  'const AUDIO_MAP = ' + JSON.stringify(map) + ';\n');
console.log(`${entries.length} lines (${entries.filter(e=>e.l==='en').length} en, ${entries.filter(e=>e.l==='es').length} es)`);

#!/usr/bin/env python3
"""Render the earnings-and-inflation section into index.html from
bls-derived.json, between the BLS-SECTION markers. Re-run after refresh."""
import json, re, pathlib

d = json.load(open("bls-derived.json"))
ref = d["_reference_month_label"]
E = d["earnings"]; C = d["cpi"]; X = d["extra"]
AHE, AWE, CPI0 = "SMU36356200500000003", "SMU36356200500000011", "CUURS12ASA0"

# Table 1 hierarchy: (item_code, indent). Mirrors the release's indentation.
TREE = [("SA0",0),("SAF",0),("SAF1",1),("SAF11",2),("SAF111",3),("SAF112",3),
        ("SAF113",3),("SAF114",3),("SAF115",3),("SAF116",3),("SEFV",2),
        ("SAF2",1),("SAH",0),("SAH1",1),("SEHA",2),("SEHC",2),("SEHC01",3),
        ("SAH3",1),("SAA",0),("SAT",0),("SAT1",1),("SETA",2),("SETA01",3),
        ("SETA02",3),("SETB",2),("SETB01",3),("SS47014",4),("SS47015",4),
        ("SS47016",4),("SAM",0),("SAR",0),("SAE",0),("SEEB",1),("SAG",0)]
by_code = {v["item_code"]: v for v in C.values()}
missing = {m["id"].replace("CUURS12A",""): m["label"] for m in d["missing"]}

def cls(p):
    return "up" if p > 0.05 else "down" if p < -0.05 else "flat"

rows = []
for code, ind in TREE:
    v = by_code.get(code)
    if not v:
        lbl = missing.get(code, code)
        rows.append(f'        <tr class="lvl{ind} unavail"><td class="item">{lbl}</td>'
                    f'<td class="num">—</td><td class="num sc">not published for this area</td></tr>')
        continue
    p = v["yoy_pct"]
    strong = ' style="font-weight:700"' if ind == 0 else ""
    rows.append(
        f'        <tr class="lvl{ind}"><td class="item"{strong}>{v["label"]}</td>'
        f'<td class="num {cls(p)}"{strong}>{p:+.1f}%</td>'
        f'<td class="num sc">{v["index"]:.1f}</td></tr>')

def stat(rec, note):
    p = rec["yoy_pct"]
    prelim = "P" in (rec.get("footnotes") or [])
    flag = ' <span class="prelim" title="BLS marks this observation preliminary; it is subject to revision.">preliminary</span>' if prelim else ""
    return f'''      <div class="cell">
        <div class="lbl">{rec["label"]}{flag}</div>
        <div class="val {cls(p)}">{p:+.1f}%</div>
        <div class="sub">{note} · {rec["month_label"]}</div>
      </div>'''

section = f'''<!-- BLS-SECTION:START (generated by build-bls-section.py — do not hand-edit) -->
  <section id="earnings-inflation">
    <h2 class="sec">Earnings and inflation</h2>
    <p class="ctrl-note" style="margin-top:0.75rem;">
      Straight from the Bureau of Labor Statistics: how fast pay is rising in the
      New York metro, and how fast prices are. Latest month common to all three
      is <b>{ref}</b>. Both earnings figures are <b>growth rates, not pay levels</b>,
      and both are <b>averages</b> — an average is pulled up by high earners and is
      not the typical worker's experience.
    </p>

    <div class="summary bls-stats">
{stat(E[AHE], "Average hourly earnings, total private")}
{stat(E[AWE], "Average weekly earnings, total private")}
{stat(C[CPI0], "CPI-U, all items")}
    </div>

    <h3 class="subsec">Inflation by expenditure category</h3>
    <p class="ctrl-note">
      Every category in Table 1 of the New York-area CPI release, year over year
      for {ref}. Indentation follows the release: indented rows are components of
      the line above them and are already counted in it, so they do not sum.
    </p>
    <table class="bls-table">
      <tr><th>Category</th><th class="num">12-month change</th><th class="num">Index</th></tr>
{chr(10).join(rows)}
    </table>
    <p class="ctrl-note" style="margin-top:0.9rem;">
      <b>Note on scope.</b> The earnings series cover private-sector payroll jobs in the
      New York-Newark-Jersey City, NY-NJ metropolitan area; the CPI covers the broader
      New York-Newark-Jersey City, NY-NJ-PA consumer market area, so the two populations
      are not identical. All series are not seasonally adjusted, which is why this
      section reports year-over-year rather than month-to-month change. Energy
      ({X["CUURS12ASA0E"]["yoy_pct"]:+.1f}%) is a special aggregate from Table 2, shown on the
      tracker above but excluded from the Table 1 list. Source:
      <a href="https://www.bls.gov/regions/northeast/news-release/consumerpriceindex_newyork.htm">BLS New York-area CPI</a>
      and <a href="https://www.bls.gov/sae/">BLS State and Metro Area Employment, Hours and Earnings</a>,
      retrieved via the BLS public API on {d["_computed"]}.
    </p>
  </section>
<!-- BLS-SECTION:END -->'''

p = pathlib.Path("index.html"); html = p.read_text()
if "BLS-SECTION:START" in html:
    html = re.sub(r"(?s)<!-- BLS-SECTION:START.*?<!-- BLS-SECTION:END -->", section, html, count=1)
else:
    anchor = '  <section class="method">'
    assert anchor in html, "method section anchor not found"
    html = html.replace(anchor, section + "\n\n" + anchor, 1)
p.write_text(html)
print(f"ok: section rendered ({len(rows)} rows, ref {ref})")

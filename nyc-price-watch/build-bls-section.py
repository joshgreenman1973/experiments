#!/usr/bin/env python3
"""Render the pay-and-prices spotlight into index.html from bls-derived.json
between the BLS-SECTION markers. Earnings come from CES only — no ECI or
QCEW, which run on different cadences and vintages. Re-run after fetch-bls.py + compute-bls.py."""
import json, re, pathlib

d = json.load(open("bls-derived.json"))
R = json.load(open("readings.json"))["items"]
ref = d["_reference_month_label"]
E = d["earnings"]; C = d["cpi"]; X = d["extra"]
AHE, AWE, CPI0 = "SMU36356200500000003", "SMU36356200500000011", "CUURS12ASA0"

def cls(p): return "up" if p > 0.05 else "down" if p < -0.05 else "flat"

def prelim(rec):
    return ('<span class="prelim" title="BLS marks this observation preliminary; it is subject to revision.">preliminary</span>'
            if "P" in (rec.get("footnotes") or []) else "")

# ---- Table 1 hierarchy (unchanged) ----
TREE = [("SA0",0),("SAF",0),("SAF1",1),("SAF11",2),("SAF111",3),("SAF112",3),
        ("SAF113",3),("SAF114",3),("SAF115",3),("SAF116",3),("SEFV",2),
        ("SAF2",1),("SAH",0),("SAH1",1),("SEHA",2),("SEHC",2),("SEHC01",3),
        ("SAH3",1),("SAA",0),("SAT",0),("SAT1",1),("SETA",2),("SETA01",3),
        ("SETA02",3),("SETB",2),("SETB01",3),("SS47014",4),("SS47015",4),
        ("SS47016",4),("SAM",0),("SAR",0),("SAE",0),("SEEB",1),("SAG",0)]
by_code = {v["item_code"]: v for v in C.values()}
missing = {m["id"].replace("CUURS12A",""): m["label"] for m in d["missing"]}
rows = []
for code, ind in TREE:
    v = by_code.get(code)
    if not v:
        rows.append(f'        <tr class="lvl{ind} unavail"><td class="item">{missing.get(code, code)}</td>'
                    f'<td class="num">—</td><td class="num sc">not published for this area</td></tr>')
        continue
    p = v["yoy_pct"]
    strong = ' style="font-weight:700"' if ind == 0 else ""
    rows.append(f'        <tr class="lvl{ind}"><td class="item"{strong}>{v["label"]}</td>'
                f'<td class="num {cls(p)}"{strong}>{p:+.1f}%</td>'
                f'<td class="num sc">{v["index"]:.1f}</td></tr>')

def pickrow(code, label):
    v = by_code[code]
    return (f'        <div class="row"><span class="k">{label}</span>'
            f'<span class="v {cls(v["yoy_pct"])}">{v["yoy_pct"]:+.1f}%</span></div>')

ahe, awe, cpi = E[AHE], E[AWE], C[CPI0]

section = f'''<!-- BLS-SECTION:START (generated by build-bls-section.py — do not hand-edit) -->
  <section id="earnings-inflation">
    <div class="spotlight">

      <div class="spot" id="spot-pay">
        <div class="spot-kicker">Pay</div>
        <div class="spot-headline {cls(ahe["yoy_pct"])}">{ahe["yoy_pct"]:+.1f}%</div>
        <div class="spot-what">Average hourly earnings, year over year · {ahe["month_label"]} {prelim(ahe)}</div>
        <div class="spot-second"><b>{awe["yoy_pct"]:+.1f}%</b> average weekly earnings, year over year {prelim(awe)}</div>
        <div class="spot-detail">
          <div class="row"><span class="k">Hourly level</span><span class="v">${ahe["level"]:.2f}</span></div>
          <div class="row"><span class="k">Weekly level</span><span class="v">${awe["level"]:,.2f}</span></div>
          <div class="row"><span class="k">Hourly, year ago</span><span class="v">${ahe["prior_year_level"]:.2f}</span></div>
          <div class="row"><span class="k">Weekly, year ago</span><span class="v">${awe["prior_year_level"]:,.2f}</span></div>
        </div>
        <div class="spot-note">Private-sector payroll jobs, New York-Newark-Jersey City, NY-NJ metro (BLS CES).
          These are growth rates of <b>averages</b> — lifted by high earners, not the typical worker's raise, and not medians.</div>
      </div>

      <div class="spot" id="spot-prices">
        <div class="spot-kicker">Prices</div>
        <div class="spot-headline {cls(cpi["yoy_pct"])}">{cpi["yoy_pct"]:+.1f}%</div>
        <div class="spot-what">Consumer prices, all items, year over year · {cpi["month_label"]}</div>
        <div class="spot-second">CPI-U index {cpi["index"]:.1f} · not seasonally adjusted</div>
        <div class="spot-detail">
{pickrow("SAH1", "Shelter")}
{pickrow("SAF11", "Food at home")}
{pickrow("SEFV", "Food away from home")}
{pickrow("SETB", "Motor fuel")}
          <div class="row"><span class="k">Energy (Table 2 special aggregate)</span><span class="v {cls(X["CUURS12ASA0E"]["yoy_pct"])}">{X["CUURS12ASA0E"]["yoy_pct"]:+.1f}%</span></div>
        </div>
        <div class="spot-note">New York-Newark-Jersey City, NY-NJ-PA consumer market area (BLS CPI-U) — a broader
          geography than the earnings panel, so the two are read side by side, not subtracted.</div>
      </div>

    </div>

    <details class="bls-cats">
      <summary><span class="sum-h">Inflation by expenditure category</span>
        <span class="sum-sub">every Table 1 line from the New York-area CPI release · {ref}</span></summary>
      <p class="ctrl-note" style="margin-top:0.8rem;">
        Indentation follows the release: indented rows are components of the line
        above them and are already counted in it, so they do not sum.
      </p>
      <table class="bls-table">
        <tr><th>Category</th><th class="num">12-month change</th><th class="num">Index</th></tr>
{chr(10).join(rows)}
      </table>
    </details>

    <p class="ctrl-note" style="margin-top:0.9rem;">
      <b>Scope.</b> Earnings cover private-sector payroll jobs in the New York-Newark-Jersey City,
      NY-NJ metro; the CPI covers the broader NY-NJ-PA consumer market area, so the populations are
      not identical. All series are not seasonally adjusted, which is why this page reports
      year-over-year rather than month-to-month change. {ref} is the latest month common to
      hourly earnings, weekly earnings and headline CPI. Source:
      <a href="https://www.bls.gov/regions/northeast/news-release/consumerpriceindex_newyork.htm">BLS New York-area CPI</a> and
      <a href="https://www.bls.gov/sae/">BLS State and Metro Area Employment, Hours and Earnings</a>,
      retrieved via the BLS public API on {d["_computed"]}.
    </p>
  </section>
<!-- BLS-SECTION:END -->'''

p = pathlib.Path("index.html"); html = p.read_text()
assert "BLS-SECTION:START" in html, "markers missing"
html = re.sub(r"(?s)<!-- BLS-SECTION:START.*?<!-- BLS-SECTION:END -->", section, html, count=1)
p.write_text(html)
print(f"ok: spotlight rendered (ref {ref}, {len(rows)} category rows)")

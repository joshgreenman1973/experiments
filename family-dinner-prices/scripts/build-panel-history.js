#!/usr/bin/env node
/**
 * Builds panel-history.js (PANEL_HISTORY) from data/panel.json + the dated
 * snapshots in data/panel-snapshots/. Drives the page's trend section.
 *
 * Usage: node scripts/build-panel-history.js
 */
const fs = require('fs');
const path = require('path');
const dataDir = path.join(__dirname, '..', 'data');
const snapDir = path.join(dataDir, 'panel-snapshots');

const panelDoc = JSON.parse(fs.readFileSync(path.join(dataDir, 'panel.json'), 'utf8'));
const files = fs.readdirSync(snapDir).filter(f => f.endsWith('.json')).sort();
if (!files.length) { console.error('No panel snapshots found. Run check-panel.js first.'); process.exit(1); }
const snaps = files.map(f => JSON.parse(fs.readFileSync(path.join(snapDir, f), 'utf8')));

const dates = snaps.map(s => s.date);
const avg = arr => arr.length ? Math.round(arr.reduce((a, b) => a + b, 0) / arr.length * 100) / 100 : null;

// City-wide + per-borough average totals per snapshot
const citywide = snaps.map(s => avg(Object.values(s.restaurants).map(r => r.total)));
const boroughs = ['Manhattan', 'Brooklyn', 'Queens', 'Bronx', 'Staten Island'];
const byBorough = {};
for (const b of boroughs) {
  byBorough[b] = snaps.map(s => avg(Object.values(s.restaurants).filter(r => r.borough === b).map(r => r.total)));
}

// Per-restaurant series + movers (latest vs baseline, only where both ends verified)
const ids = Object.keys(panelDoc.panel);
const first = snaps[0], last = snaps[snaps.length - 1];
const movers = [];
const panelList = ids.map(id => {
  const p = panelDoc.panel[id];
  const series = snaps.map(s => s.restaurants[id]?.total ?? null);
  const baseTot = first.restaurants[id]?.total ?? p.baselineTotal;
  const lastTot = last.restaurants[id]?.total ?? null;
  const change = (lastTot != null && baseTot != null) ? Math.round((lastTot - baseTot) * 100) / 100 : 0;
  if (snaps.length >= 2 && change !== 0 && last.restaurants[id]?.fullyVerified) {
    movers.push({ name: p.name, borough: p.borough, change });
  }
  return {
    id, name: p.name, borough: p.borough, cuisine: p.cuisine, neighborhood: p.neighborhood,
    items: {
      adultEntree: p.pinned.adultEntree, kidMeal: p.pinned.kidMeal,
      appetizer: p.pinned.appetizer, drinks: p.pinned.drinks,
    },
    baselineTotal: baseTot, latestTotal: lastTot, series,
    fullyVerified: last.restaurants[id]?.fullyVerified ?? false,
  };
});
movers.sort((a, b) => Math.abs(b.change) - Math.abs(a.change));

const latest = last;
const fullyVerified = Object.values(latest.restaurants).filter(r => r.fullyVerified).length;

const out = {
  generatedAt: new Date().toISOString(),
  baselineDate: panelDoc.meta.baselineDate,
  snapshotCount: snaps.length,
  dates,
  trends: { citywide, byBorough },
  movers,
  panel: panelList,
  stats: {
    count: ids.length,
    fullyVerified,
    sodaPrice: panelDoc.meta.sodaPrice,
    formula: panelDoc.meta.formula,
  },
};

const header = `// Auto-generated by build-panel-history.js — do not edit\n// Generated: ${out.generatedAt}\n// Panel snapshots: ${snaps.length}\n\n`;
fs.writeFileSync(path.join(__dirname, '..', 'panel-history.js'), header + 'const PANEL_HISTORY = ' + JSON.stringify(out, null, 2) + ';\n');
console.log(`Wrote panel-history.js — ${ids.length} restaurants, ${snaps.length} snapshot(s), city avg $${citywide[citywide.length - 1]}`);
